// Generates docs/script-api.md from the script typings Monaco uses
// (src/editor/scriptTypes.ts), so the reference can't drift from what the
// editor type-checks. `node scripts/gen-docs.mjs` rewrites the file;
// src/editor/docs.test.ts fails when it is out of date.

import { readFileSync, writeFileSync } from 'node:fs'

/** The public, versioned script API: changes to these only happen in a major release. */
const ORDER = [
  ['Script', 'What a script file exports. Every hook is optional.'],
  ['Context', 'The `ctx` every hook receives: the entity it runs on plus the engine services.'],
  ['Handle', 'An entity as scripts see it (also what `find`, `spawn` and collision hooks give you).'],
  ['RigidBody', '`ctx.body`, when the entity has a Rigid Body.'],
  ['Input', '`ctx.input`: keyboard, mouse, gamepad and touch, through the actions and axes in Project Settings.'],
  ['Time', '`ctx.time`.'],
  ['Physics', '`ctx.physics`: queries and forces.'],
  ['PhysicsHit', 'A raycast or sphere-cast result.'],
  ['Nav', '`ctx.nav`: pathfinding over the scene.'],
  ['Animation', '`ctx.animation`, when the entity has a Model.'],
  ['Particles', '`ctx.particles`, when the entity has a Particle Emitter.'],
  ['Sound', '`ctx.sound`: one-shot sounds and a small synth.'],
  ['AudioSource', '`ctx.audio`, when the entity has an Audio Source.'],
  ['Ui', '`ctx.ui`: screen UI built from scripts.'],
  ['UiStyle', 'Placement and look of `ctx.ui` elements.'],
  ['Hud', '`ctx.hud`: the stat cards and messages at the top of the screen.'],
  ['Timer', 'What `after` and `every` return.'],
  ['TweenOptions', 'Options for `ctx.tween`.'],
  ['Vec3Like', 'Any `{ x, y, z }`, including three.js vectors.'],
]

/** Extracts the declaration text from scriptTypes.ts. */
function declarations(source) {
  const start = source.indexOf('export const SCRIPT_TYPES = `') + 'export const SCRIPT_TYPES = `'.length
  return source.slice(start, source.indexOf('\n`', start))
}

/** The body of `interface Name … { … }` (balanced braces), its heading line and `extends`. */
function interfaceBody(text, name) {
  const match = new RegExp(`interface ${name}\\b([^{]*)\\{`).exec(text)
  if (!match) throw new Error(`interface ${name} not found in scriptTypes.ts`)
  let i = match.index + match[0].length
  let depth = 1
  const start = i
  for (; depth > 0; i++) {
    if (text[i] === '{') depth++
    else if (text[i] === '}') depth--
  }
  // Drop generic parameters (`<P extends Record<…>>`) before looking for the interface's own `extends`.
  let heading = match[1]
  for (let prev = ''; prev !== heading; ) [prev, heading] = [heading, heading.replace(/<[^<>]*>/g, '')]
  const extendsMatch = /extends (\w+)/.exec(heading)
  return { body: text.slice(start, i - 1), extends: extendsMatch?.[1] }
}

/** Splits an interface body into top-level members with their doc comments. */
function membersOf(body) {
  // A one-line body: `{ a: number; b(): void }`.
  if (!body.includes('\n')) {
    return body
      .split(';')
      .map((s) => s.trim())
      .filter(Boolean)
      .map((signature) => ({ signature, doc: '' }))
  }
  const members = []
  let doc = ''
  let current = null
  let depth = 0
  for (const raw of body.split('\n')) {
    const line = raw.trim()
    if (!line) continue
    if (depth === 0 && line.startsWith('/**')) {
      doc = line.replace(/^\/\*\*\s?/, '').replace(/\s?\*\/$/, '')
      if (!line.endsWith('*/')) doc += ' '
      continue
    }
    if (depth === 0 && line.startsWith('*')) {
      doc += line.replace(/^\*\/?\s?/, '').replace(/\s?\*\/$/, '') + ' '
      continue
    }
    if (depth === 0) {
      current = { signature: line, doc: doc.trim() }
      members.push(current)
      doc = ''
    } else current.signature += ` ${line}`
    for (const c of line) {
      if (c === '{' || c === '(') depth++
      else if (c === '}' || c === ')') depth--
    }
  }
  return members.map((m) => ({ ...m, signature: m.signature.replace(/\s+/g, ' ').replace(/\{ (\w)/g, '{ $1') }))
}

const nameOf = (signature) => /^(?:readonly\s+)?([A-Za-z_]\w*)/.exec(signature)?.[1] ?? signature

export function generate(source) {
  const text = declarations(source)
  const out = [
    '# Script API reference',
    '',
    '<!-- Generated by scripts/gen-docs.mjs from src/editor/scriptTypes.ts. Do not edit by hand: run `node scripts/gen-docs.mjs`. -->',
    '',
    'Scripts are JavaScript modules that export an object; the editor type-checks them against these declarations (the same ones listed here).',
    '',
    '```js',
    "/** @type {import('engine').Script} */",
    'export default {',
    '  params: { speed: 4 },',
    '  update(ctx, dt) {',
    "    ctx.object.position.x += ctx.input.getAxis('MoveX') * ctx.params.speed * dt",
    '  },',
    '}',
    '```',
    '',
    '## Stability',
    '',
    'Everything on this page is the public script API. From version 1.0 it follows semantic versioning: members are only removed or changed in a major release, and new members can arrive in any minor release. Anything not listed here (for example `ctx.engine`, which exposes engine internals) can change at any time.',
    '',
    'Scripts also get `THREE` (three.js) and `helpers` (`damp`, `dampAngle`, `moveTowards`, `teleport`) as globals.',
    '',
    '## Contents',
    '',
    ...ORDER.map(([name]) => `- [${name}](#${name.toLowerCase()})`),
    '',
  ]
  for (const [name, intro] of ORDER) {
    const { body, extends: base } = interfaceBody(text, name)
    out.push(`## ${name}`, '', intro + (base ? ` Also has every member of [${base}](#${base.toLowerCase()}).` : ''), '')
    for (const member of membersOf(body)) {
      out.push(`- **\`${nameOf(member.signature)}\`** — \`${member.signature.replace(/`/g, "'")}\``)
      if (member.doc) out.push(`  ${member.doc}`)
    }
    out.push('')
  }
  return out.join('\n')
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const source = readFileSync(new URL('../src/editor/scriptTypes.ts', import.meta.url), 'utf8')
  writeFileSync(new URL('../docs/script-api.md', import.meta.url), generate(source))
  console.log('wrote docs/script-api.md')
}
